"""Add the Tempest boot logo (design E without FIRMWARE, 2026-11-25) to a finished Dnnn build.
usage: build_logo.py IN.bin OUT.bin [REV]      e.g. build_logo.py ..._D009_waterfall.bin ..._D009.bin D009
1) logo.c (+ logo_data.h generated here from ../mock_bootlogo.py geometry) is compiled with clang and
   appended after the image; the boot paint call 0x15190 (bl 0x2baa4 = draw the 40 KB RGB565 picture
   from flash 0x74000) becomes bl logo_draw.
2) The firmware now owns 0x74000-0x7DFFF, so the CPS boot-picture upload must not erase/write it:
   0x2bade (erase the 5 picture sectors) and 0x2bb34 (zero + erase + write) -> bx lr,
   0x2baba (write a picture packet) -> return 1 (= success, so CPS finishes without an error).
3) Image may now run to 0x7E000 (0x7E000-0x7FFFF is left alone)."""
import sys, os, struct, hashlib, subprocess, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from keystone import Ks, KS_ARCH_ARM, KS_MODE_THUMB
src, out = sys.argv[1:3]
d = bytearray(open(src, 'rb').read())
B = 0x4000
i = d.find(b'V%d.%d.%d.%03d'); assert i > 0
REV = sys.argv[3] if len(sys.argv) > 3 else d[i+14:i+20].split(b'\0')[0].decode()
assert REV.startswith('D'), REV
d += b'\0' * (-len(d) % 4)
ORG = B + len(d)

# ---- tables from the mockup ------------------------------------------------------------------
import mock_bootlogo as M
HS = [3, 4, 3, 5, 4, 6, 5, 8, 7, 11, 14, 20, 28, 36, 42, 36, 28, 20, 14, 11, 7, 8, 5, 6, 4, 5, 3, 4, 3]
import inspect
assert 'hs = ' + str(HS) in inspect.getsource(M.opt_e), 'bar heights changed in mock_bootlogo.opt_e'
import math
SX0, SX1 = 8, 151
sy = [66 + int(5 * math.sin(x / 7.0) * math.exp(-((x - 80) / 50.0) ** 2)) for x in range(SX0, SX1 + 1)]
dl = [b - a for a, b in zip(sy, sy[1:])]; assert all(-1 <= v <= 1 for v in dl)
SD = bytearray((len(dl) + 3) // 4)
for k, v in enumerate(dl): SD[k >> 2] |= (v + 1) << ((k & 3) * 2)
sc, gap, wy = 0.86, 3, 78
cx = 80 - M.word_w('TEMPEST', sc, gap) // 2; WR = []
for ch in 'TEMPEST':
    for (a, b, e, f) in M.G[ch]:
        WR.append((cx + int(a * sc), wy + int(b * sc), cx + int((e + 1) * sc) - 1, wy + int((f + 1) * sc) - 1))
    cx += int(16 * sc) + gap
VER = 'V1.01.14.002 ' + REV
hdr = f'''/* generated by build_logo.py - do not edit */
#define NBAR {len(HS)}
#define BASE 60
#define BW 5
#define BX0 {80 - (len(HS) * 5) // 2}
static const u8 HS[NBAR] = {{{', '.join(map(str, HS))}}};
#define SX0 {SX0}
#define SX1 {SX1}
#define SY0 {sy[0]}
static const u8 SD[{len(SD)}] = {{{', '.join(map(str, SD))}}};
#define NRECT {len(WR)}
static const u8 WR[NRECT][4] = {{{', '.join('{%d,%d,%d,%d}' % r for r in WR)}}};
static const char VER[] = "{VER}";
#define VER_Y 118
'''
open(os.path.join(HERE, 'logo_data.h'), 'w').write(hdr)

# ---- compile + link at ORG -------------------------------------------------------------------
T = tempfile.mkdtemp()
F = '--target=armv7em-none-eabi -mcpu=cortex-m4 -mthumb -mfloat-abi=soft -Oz -ffreestanding -fno-builtin -nostdlib -Wall -fno-common -fno-jump-tables'.split()
subprocess.check_call(['clang', *F, '-c', os.path.join(HERE, 'logo.c'), '-o', T + '/logo.o'])
open(T + '/l.ld', 'w').write('MEMORY { C (rx) : ORIGIN = %#x, LENGTH = 0x4000 }\nSECTIONS { .text : { *(.text.start) *(.text*) *(.rodata*) } > C\n'
                              '  .data : { *(.data*) *(.bss*) *(COMMON) } > C\n  /DISCARD/ : { *(.ARM.*) *(.comment) } }\n' % ORG)
subprocess.check_call(['ld.lld', '-T', T + '/l.ld', T + '/logo.o', '-o', T + '/logo.elf'])
subprocess.check_call(['llvm-objcopy', '-O', 'binary', T + '/logo.elf', T + '/logo.bin'])
nm = subprocess.check_output(['llvm-nm', T + '/logo.elf']).decode().split('\n')
sym = {l.split()[2]: int(l.split()[0], 16) for l in nm if len(l.split()) == 3}
assert sym['logo_draw'] == ORG, hex(sym['logo_draw'])
assert not any(s.split()[1] in 'bBdD' for s in nm if len(s.split()) == 3), 'logo must not use RAM'
code = open(T + '/logo.bin', 'rb').read()
d += code + b'\0' * (-len(code) % 4)

# ---- patches -----------------------------------------------------------------------------------
ks = Ks(KS_ARCH_ARM, KS_MODE_THUMB)
def asm(s, a): return bytes(ks.asm(s, a)[0])
def patch(addr, old, new):
    o = addr - B; assert d[o:o+len(old)] == old, (hex(addr), d[o:o+len(old)].hex()); assert len(old) == len(new)
    d[o:o+len(new)] = new
patch(0x15190, asm('bl 0x2baa4', 0x15190), asm('bl %#x' % ORG, 0x15190))
patch(0x2bade, bytes.fromhex('10b5'), bytes.fromhex('7047'))                       # bx lr
patch(0x2bb34, bytes.fromhex('10b5'), bytes.fromhex('7047'))                       # bx lr
patch(0x2baba, bytes.fromhex('10b58b18'), bytes.fromhex('01207047'))               # movs r0,#1; bx lr
END = B + len(d)
assert END <= 0x7E000, f'image ends at {END:#x}: must stay below 0x7E000'
open(out, 'wb').write(d)
print(out, f'logo {len(code)} B at {ORG:#x}, ends {END:#x} ({0x76000 - END:+d} B vs 0x76000)', hashlib.sha256(d).hexdigest())
