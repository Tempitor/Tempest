/* Tempest boot logo (design E, 2026-11-25): drawn with the stock emWin calls in place of the
   40 KB boot picture at 0x74000. Called from the boot paint at 0x15190 (was bl 0x2baa4).
   Tables (bar heights, sine deltas, wordmark rects, version text) come from logo_data.h,
   generated by build_logo.py from tools/vfo3/mock_bootlogo.py so the radio matches the mockup. */
typedef unsigned int u32; typedef unsigned char u8; typedef signed char s8;
#define FN(a,t) ((t)((a)|1))
#define GUI_SetColor       FN(0x42b96,u32(*)(u32))
#define GUI_SetFont        FN(0x42bd0,const void*(*)(const void*))
#define GUI_SetTextMode    FN(0x42cc4,int(*)(int))
#define GUI_FillRect       FN(0x41ad8,void(*)(int,int,int,int))
#define GUI_DispStrHCenter FN(0x410a8,void(*)(const char*,int,int))   /* (s, centre x, y), sets TA_HCENTER */
#define LCD_Flush          FN(0xf18c,void(*)(void))
#define FONT8 ((const void*)0x68918)
#include "logo_data.h"

#define TEAL  0x00B8A8u
#define ROYAL 0x2448DCu
#define AQUA  0x60F0DCu
#define WHITE 0xFFFFFFu
#define GREY  0x788CA0u
#define NAVY  0x000C30u

/* channel-wise a + (b-a)*num/den, rounded down like the mockup's int() */
__attribute__((noinline)) static u32 mix(u32 a, u32 b, int num, int den) {
  u32 c = 0;
  for (int s = 0; s < 24; s += 8) {
    int x = (a >> s) & 255, y = (b >> s) & 255;
    c |= (u32)((x * den + (y - x) * num) / den) << s;
  }
  return c;
}
__attribute__((noinline)) static void rect(u32 c, int x0, int y0, int x1, int y1) { GUI_SetColor(0xFF000000u | c); GUI_FillRect(x0, y0, x1, y1); }

__attribute__((section(".text.start"))) void logo_draw(void) {
  rect(0, 0, 64, 159, 127);                                         /* black lower half */
  for (int y = 0; y < 64; y++) rect(mix(0, NAVY, y, 63), 0, y, 159, y);   /* black -> navy */
  for (int i = 0; i < NBAR; i++) {                                  /* spectrum bars */
    int top = BASE - HS[i], d = i - NBAR / 2, den = BASE - top, xa = BX0 + i * BW;
    if (d < 0) d = -d;
    if (den < 1) den = 1;
    for (int y = top; y <= BASE; y++)
      rect(d ? mix(TEAL, ROYAL, (y - top) * 29 + 8 * d * den, 145 * den) : AQUA, xa, y, xa + BW - 2, y);
  }
  int y = SY0;                                                      /* damped sine, 2-bit deltas */
  for (int x = SX0; x <= SX1; x++) {
    if (x > SX0) { int k = x - SX0 - 1; y += ((SD[k >> 2] >> ((k & 3) * 2)) & 3) - 1; }
    rect(ROYAL, x, y, x, y);
  }
  for (int i = 0; i < NRECT; i++)                                   /* TEMPEST wordmark */
    rect(WHITE, WR[i][0], WR[i][1], WR[i][2], WR[i][3]);
  const void *of = GUI_SetFont(FONT8); int om = GUI_SetTextMode(2);
  GUI_SetColor(0xFF000000u | GREY); GUI_DispStrHCenter(VER, 80, VER_Y);
  GUI_SetTextMode(om); GUI_SetFont(of);
  LCD_Flush();
}
